package com.fixinh.sbp.modules.booking.model;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalTime;
import java.util.List;
import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.Indexed;
import org.springframework.data.mongodb.core.mapping.Document;
import com.fixinh.sbp.common.sharding.Region;
import com.fixinh.sbp.modules.customer.model.Address;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * A service booking (API Documentation Section 7, Req 3.3.S1–S2).
 *
 * <p>SMP owns the authoritative booking; this document is SBP's own projection of it, which is
 * why the customer-facing screens keep working when SMP does not (API Doc §2.8). {@code
 * bookingRef} is SMP's identifier — the one the customer sees and every URL and integration call
 * uses — while {@link #id} is Mongo's own, never exposed.
 *
 * <p><b>This document lives in exactly one shard</b>, the one named by {@link #homeRegion} — the
 * same store that owns the customer who made the booking, not the store {@link #serviceAddress}
 * would resolve to. A booking's own address may name a different province from the customer's
 * registered one (the customer can request work somewhere else), so the two are deliberately
 * decided independently. See {@code ShardedServiceBookingRepository}.
 */
@Document(collection = "bookings")
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class ServiceBooking {

	/** Mongo's _id. Internal only — never returned by an endpoint. */
	@Id
	private String id;
	/** Human-readable, unique, ORD-YYYY-NNNN (API Doc §2.6). Generated by SMP at creation. */
	@Indexed(unique = true)
	private String bookingRef;
	/** Owner. Always read from the JWT sub, never from a request body (Req A.2.a). */
	@Indexed
	private String customerId;
	/** From the repair-service catalogue (GET /reference/repair-services). */
	private String serviceId;
	/**
	 * Snapshot of the catalogue's name at booking time, so a later catalogue rename does not
	 * relabel a booking already made.
	 */
	private String serviceName;
	/**
	 * Snapshot, in VND, of the catalogue's base fee at booking time (Req: "calculate total price
	 * based on service"). Not returned by POST /bookings — the doc's response shape there is
	 * bookingRef/status/serviceName/preferredServiceDate/createdAt/message only — but held here
	 * for the eventual bill, where Total Cost = Service Fee + Material Cost (Req 3.3.S6).
	 */
	private long baseServiceFee;
	/** What is wrong, in the customer's words. 10 to 1000 characters. */
	private String issueDescription;
	/** Today or later at submission time (Req: schedule time must be future). */
	private LocalDate preferredServiceDate;
	private LocalTime availableStartTime;
	/** Strictly after {@link #availableStartTime}, at least 60 minutes later. */
	private LocalTime availableEndTime;
	/**
	 * Where the work happens. A snapshot copied onto the booking at creation, independent of the
	 * customer's profile address — editing the profile later does not rewrite a job already
	 * booked.
	 */
	private Address serviceAddress;
	private BookingStatus status;
	private Instant createdAt;
	/**
	 * Present only once SMP has scheduled technicians for this job (status SCHEDULED — API Doc
	 * §7.2's own note). Null until SMP pushes that change through §11.7, which nothing does yet.
	 */
	private Instant scheduledStartAt;
	/** Alongside {@link #scheduledStartAt} — set together, absent together. */
	private Integer estimatedDurationMinutes;
	/** Who is assigned, once assigned. Null (not empty) until then, same reasoning. */
	private List<TechnicianRef> technicians;
	/**
	 * The billed total once the booking is COMPLETED (Req 3.3.S6). Null until SMP marks it so —
	 * {@code serviceFee + materialCost}, computed on SMP's side, not recomputed here.
	 */
	private Long totalCost;
	/** Which shard holds the authoritative copy — the customer's home region, not the job's. */
	private Region homeRegion;
}
